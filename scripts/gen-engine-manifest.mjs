// Generates src/lib/engine/manifest.js from the pinned pyodide npm package's
// lockfile, so the app knows — before downloading anything — exactly which
// files each analysis needs. Run after bumping the `pyodide` devDependency:
//   yarn engine:manifest
import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('pyodide/package.json'));
const { version } = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
const lock = JSON.parse(readFileSync(join(pkgDir, 'pyodide-lock.json'), 'utf8'));

// Top-level packages the app may request. Dependencies are resolved below.
const ROOTS = ['numpy', 'scipy'];

// Wheels are not shipped in the npm package, so their sizes are estimates
// used only until the CDN response's Content-Length arrives.
const ESTIMATED_BYTES = { numpy: 3_600_000, openblas: 1_600_000, scipy: 13_500_000 };

const CORE_FILES = ['pyodide.mjs', 'pyodide.asm.js', 'pyodide.asm.wasm', 'python_stdlib.zip', 'pyodide-lock.json'];

const packages = {};
const visit = (name) => {
  if (packages[name]) return;
  const p = lock.packages[name];
  if (!p) throw new Error(`Package ${name} not in pyodide-lock.json`);
  packages[name] = {
    file: p.file_name,
    sha256: p.sha256,
    depends: p.depends,
    bytes: ESTIMATED_BYTES[name] ?? 1_000_000,
  };
  p.depends.forEach(visit);
};
ROOTS.forEach(visit);

const core = CORE_FILES.map((file) => ({ file, bytes: statSync(join(pkgDir, file)).size }));

const out = `// AUTO-GENERATED by scripts/gen-engine-manifest.mjs — do not edit by hand.
// Pyodide ${version} (Python ${lock.info.python}).

export const PYODIDE_VERSION = '${version}';
export const PYODIDE_CDN = 'https://cdn.jsdelivr.net/pyodide/v${version}/full/';

/** Files fetched by loadPyodide() itself (exact sizes from the npm package). */
export const CORE_FILES = ${JSON.stringify(core, null, 2)};

/** Wheels per package; \`bytes\` are estimates until Content-Length is known. */
export const PACKAGES = ${JSON.stringify(packages, null, 2)};
`;
writeFileSync(new URL('../src/lib/engine/manifest.js', import.meta.url), out);
console.log(`Wrote engine manifest for pyodide ${version}: ${Object.keys(packages).join(', ')}`);
